def add_round_key(state, round_key):

    for i in range(4):
        for j in range(4):
            state[i][j] ^= round_key[i][j]

    return state

state = [
    [0x19, 0xa0, 0x9a, 0xe9],
    [0x3d, 0xf4, 0xc6, 0xf8],
    [0xe3, 0xe2, 0x8d, 0x48],
    [0xbe, 0x2b, 0x2a, 0x08]
]

round_key = [
    [0xa0, 0x88, 0x23, 0x2a],
    [0xfa, 0x54, 0xa3, 0x6c],
    [0xfe, 0x2c, 0x39, 0x76],
    [0x17, 0xb1, 0x39, 0x05]
]

result = add_round_key(state, round_key)    
for row in result:
    print([hex(x) for x in row])